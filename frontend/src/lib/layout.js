// ============================================================
// 피그마 좌표 → 화면 위치 계산
//
// ★ 이 파일 덕분에 화면 코드에는 "피그마에 뜨는 숫자 그대로" 적으면 됩니다.
//   피그마에서 무언가를 클릭하면 오른쪽 패널에 X · Y · W 가 나옵니다.
//   그 숫자를 그냥 옮겨 적으세요. % 계산은 여기서 다 합니다.
// ============================================================

// 시안 전체 크기와 위아래 하늘색 띠 높이 (background.svg 에서 그대로 가져온 값)
export const FRAME = { w: 2560, h: 1440, bandTop: 244, bandBottom: 64 };

// 띠 사이의 "책상" 영역
export const DESK = { y: FRAME.bandTop, h: FRAME.h - FRAME.bandTop - FRAME.bandBottom }; // 244, 1132

// ------------------------------------------------------------
// 펼쳐진 다이어리(diary2.svg) 가 놓이는 자리
//
// 다이어리 몸통(손잡이 뺀 1269.6) 을 화면 한가운데 두고,
// 책상 영역에서 위아래 가운데 정렬한 값입니다.
// 이름 입력 화면의 좌표들(회색 모이모 X 1156+W 243, 입력칸 987~버튼 1567)이
// 전부 화면 한가운데 1280 을 중심으로 놓여 있어서 이렇게 나옵니다.
// ------------------------------------------------------------
export const TABLET = {
  x: (FRAME.w - 1269.6) / 2, // 645.2
  y: DESK.y + (DESK.h - 894) / 2, // 363
  w: 1403,
  h: 894,
};

// 다이어리 안쪽 "맨 앞 흰 종이" 자리 (diary2.svg 안 rect 를 프레임 좌표로 옮긴 것)
export const SCREEN = {
  x: TABLET.x + 83.39, // 728.59
  y: TABLET.y + 61.2, // 424.2
  w: 1102.74,
  h: 770.4,
};

/** 책상(위아래 띠 사이) 위에 놓습니다. 메인 화면 물건들과 홈 버튼용. */
export function onDesk({ x, y, w }) {
  return {
    left: `${(x / FRAME.w) * 100}%`,
    top: `${((y - DESK.y) / DESK.h) * 100}%`,
    width: `${(w / FRAME.w) * 100}%`,
  };
}

/** 다이어리 안쪽 흰 종이 위에 놓습니다. 이름 입력 등 화면 내용용. */
export function onScreen({ x, y, w }) {
  return {
    left: `${((x - SCREEN.x) / SCREEN.w) * 100}%`,
    top: `${((y - SCREEN.y) / SCREEN.h) * 100}%`,
    width: `${(w / SCREEN.w) * 100}%`,
  };
}
