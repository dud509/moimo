#!/bin/bash
# ============================================================
# 프로젝트를 데스크탑 밖으로 옮깁니다 (한 번만 실행하면 됩니다)
#
#   /Users/dud/Desktop/moimo   →   /Users/dud/moimo
#
# 왜 옮기나요?
#   맥의 "데스크탑 및 문서 폴더" iCloud 동기화가 켜져 있으면,
#   데스크탑 안의 파일을 읽을 때마다 iCloud 를 거칩니다.
#   우리 프로젝트는 파일이 몇만 개라서 서버 켜는 데 1분씩 걸렸습니다.
#   동기화가 안 되는 곳으로 옮기면 몇 초로 줄어듭니다.
#
# 쓰는 법 — 터미널에 이 한 줄:
#   bash ~/Desktop/moimo/scripts/move-project.sh
#
# 옮겨도 안에 든 것(코드·그림·깃 기록)은 하나도 안 바뀝니다.
# 폴더가 통째로 자리만 옮기는 것뿐입니다.
# ============================================================

set -e

# 이 스크립트 자신도 옮겨질 폴더 안에 있습니다.
# 옮기는 도중에 스스로를 못 읽는 일이 없도록, 임시 자리로 복사해서 거기서 실행합니다.
COPY="/tmp/moimo-move.sh"
if [ "$0" != "$COPY" ]; then
  cp "$0" "$COPY"
  exec bash "$COPY" "$@"
fi

FROM="$HOME/Desktop/moimo"
TO="$HOME/moimo"

echo ""
echo "──────────────────────────────────────────"
echo "  모이모 폴더 옮기기"
echo "──────────────────────────────────────────"
echo "  지금 자리 : $FROM"
echo "  옮길 자리 : $TO"
echo ""

if [ ! -d "$FROM" ]; then
  echo "❌ 데스크탑에 moimo 폴더가 없습니다."
  if [ -d "$TO" ]; then
    echo "   이미 $TO 로 옮겨져 있네요. 더 할 일이 없습니다."
  else
    echo "   폴더 위치를 확인해 주세요."
  fi
  exit 0
fi

if [ -e "$TO" ]; then
  echo "❌ $TO 에 이미 뭔가 있습니다."
  echo "   덮어쓰면 위험하니 그냥 멈춥니다."
  echo "   그 폴더를 먼저 확인하고 치운 뒤에 다시 실행해 주세요."
  exit 1
fi

# 1. 돌고 있는 서버를 끕니다. (안 끄면 옮긴 뒤에 엉뚱한 자리를 쳐다봅니다)
echo "1/3  돌고 있는 서버를 끕니다..."
lsof -ti:5173,4000 2>/dev/null | xargs kill -9 2>/dev/null || true

# 2. 폴더를 통째로 옮깁니다.
echo "2/3  폴더를 옮깁니다... (파일이 많아서 조금 걸릴 수 있습니다)"
mv "$FROM" "$TO"

# 3. 예전 자리를 기억하고 있는 임시 파일을 지웁니다. 없으면 알아서 다시 만듭니다.
echo "3/3  임시 파일을 정리합니다..."
rm -rf "$TO/frontend/node_modules/.vite"

echo ""
echo "✅ 다 옮겼습니다."
echo ""
echo "──────────────────────────────────────────"
echo "  이제 이렇게 하세요"
echo "──────────────────────────────────────────"
echo ""
echo "  1) VS 코드에서  파일 → 폴더 열기  를 누르고"
echo "     홈 안에 있는  moimo  폴더를 고릅니다."
echo "     (데스크탑에 있던 창은 닫으세요. 이제 빈 자리를 보고 있습니다)"
echo ""
echo "  2) 터미널을 새로 열고:"
echo ""
echo "         cd ~/moimo"
echo "         npm run dev"
echo ""
echo "  앞으로 폴더 주소는  ~/moimo  입니다."
echo "  (~ 는 '내 홈 폴더' 라는 뜻이에요. /Users/dud 와 같은 말입니다)"
echo ""
